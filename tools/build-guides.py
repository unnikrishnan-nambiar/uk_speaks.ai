"""Build guides/index.html: one card per guide, newest first.

Reads every g/<slug>/index.html (skipping g/_template) plus the public
which-ai/ page, and takes each card's details from the page itself:
  title       <meta property="og:title">
  summary     <meta name="description">
  keyword     the <span class="label keyword"> chip
  added       the date the page was first committed (git), else today

The deploy workflow runs this on every push, so a new guide shows up here
without editing anything. Run it locally to preview:

    python3 tools/build-guides.py

Standard library only.
"""

import datetime
import html
import re
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "guides" / "index.html"
BASE_URL = "https://unnikrishnan-nambiar.github.io/uk_speaks.ai/"

COPY_ICON = (
    '<svg class="icon" width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
    'stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">'
    '<rect x="9" y="9" width="12" height="12" rx="2"/><path d="M5 15V5a2 2 0 0 1 2-2h10"/></svg>'
)


def meta(page, attr, name):
    m = re.search(r'<meta %s="%s" content="([^"]*)"' % (attr, re.escape(name)), page)
    return html.unescape(m.group(1)) if m else ""


def keyword(page):
    m = re.search(r'<span class="label keyword">([^<]*)</span>', page)
    return html.unescape(m.group(1)).strip() if m else ""


def first_commit(path):
    """(unix time, date) of the commit that added path, or now if uncommitted."""
    try:
        out = subprocess.run(
            ["git", "log", "--diff-filter=A", "--format=%ct", "--", str(path)],
            cwd=ROOT, capture_output=True, text=True, check=True,
        ).stdout.split()
    except (OSError, subprocess.CalledProcessError):
        out = []
    ts = int(out[-1]) if out else int(datetime.datetime.now().timestamp())
    return ts, datetime.date.fromtimestamp(ts)


def collect():
    pages = [p for p in sorted(ROOT.glob("g/*/index.html")) if p.parent.name != "_template"]
    pages.append(ROOT / "which-ai" / "index.html")
    guides = []
    for path in pages:
        page = path.read_text(encoding="utf-8")
        rel = path.parent.relative_to(ROOT).as_posix() + "/"
        ts, added = first_commit(path)
        guides.append({
            "path": rel,
            "title": meta(page, "property", "og:title") or path.parent.name,
            "summary": meta(page, "name", "description"),
            "keyword": keyword(page) or "Guide",
            "ts": ts,
            "added": added,
            "public": not rel.startswith("g/"),
        })
    guides.sort(key=lambda g: g["ts"], reverse=True)
    return guides


def card(g, i):
    e = html.escape
    url = BASE_URL + g["path"]
    access = "Public" if g["public"] else "Hidden · DM only"
    return f"""      <li class="card guide-item">
        <div class="guide-tags">
          <span class="label keyword">{e(g['keyword'])}</span>
          <span class="guide-meta">{access} · {g['added'].strftime('%-d %b %Y')}</span>
        </div>
        <h2 class="card-link-title"><a href="../{e(g['path'])}">{e(g['title'])}</a></h2>
        <p class="card-text">{e(g['summary'])}</p>
        <div class="guide-url on-ink">
          <p class="prompt-text" id="url-{i}">{e(url)}</p>
          <button class="copy-btn" type="button" data-copy-target="url-{i}">
            {COPY_ICON}
            <span class="copy-label" aria-live="polite">Copy</span>
          </button>
        </div>
      </li>
"""


def build():
    guides = collect()
    hidden = sum(1 for g in guides if not g["public"])
    cards = "".join(card(g, i) for i, g in enumerate(guides, 1))
    page = f"""<!doctype html>
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <meta name="robots" content="noindex, nofollow">
  <title>All guides — uk_speaks.ai</title>
  <meta name="description" content="Every uk_speaks.ai guide in one place, newest first.">
  <meta name="theme-color" content="#0a0a0a">

  <!-- GENERATED by tools/build-guides.py on every deploy. Don't edit by hand. -->

  <link rel="icon" href="../favicon.svg" type="image/svg+xml">
  <link rel="icon" href="../favicon-32.png" type="image/png" sizes="32x32">
  <link rel="apple-touch-icon" href="../apple-touch-icon.png">

  <link rel="preload" href="../assets/fonts/plus-jakarta-sans-800.woff2" as="font" type="font/woff2" crossorigin>
  <link rel="stylesheet" href="../assets/css/site.css?v=20">
  <script src="../assets/js/copy.js?v=2" defer></script>
</head>
<body>
  <main class="page guide">
    <header class="topbar">
      <a class="brand" href="../">uk_speaks.ai</a>
      <span class="label">All guides</span>
    </header>

    <section class="card guide-intro">
      <span class="label keyword">Guides</span>
      <h1 class="guide-title">Every guide, <span class="underline">in one place.</span></h1>
      <p class="card-text">{len(guides)} guides, newest first. {hidden} are hidden pages sent by DM; copy a link to share it.</p>
    </section>

    <ul class="guide-list">
{cards}    </ul>

    <footer class="closer on-ink">
      <h2 class="closer-title">Learn it with me<br>on Instagram.</h2>
      <a class="btn-primary" href="https://www.instagram.com/uk_speaks.ai/">
        <svg class="icon" width="20" height="20" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"><rect x="3" y="3" width="18" height="18" rx="5"/><circle cx="12" cy="12" r="4"/><circle cx="17.5" cy="6.5" r="0.8"/></svg>
        Follow @uk_speaks.ai
      </a>
      <p class="closer-note"><a href="../">Visit the uk_speaks.ai website →</a></p>
    </footer>
  </main>
</body>
</html>
"""
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(page, encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(guides)} guides")


if __name__ == "__main__":
    build()
